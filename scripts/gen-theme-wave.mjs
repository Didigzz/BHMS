// Generates the @keyframes theme-wipe-in block for the theme-switch reveal.
//
// The reveal is a "wave": the new theme's visible region grows from the
// top-left corner, bounded by a wavy front line x+y = C that sweeps toward the
// bottom-right corner (C goes 0 → 200). The front edge undulates because the
// boundary vertices are offset along the (1,1) diagonal by a sine of their
// position along the front.
//
//   - Progress p in [0,1]; C = 200p.
//   - T  = top-edge walk end      = (min(C,100), 0)
//   - R  = front upper end        = (C,0)                    if C ≤ 100
//                                 = (100, C-100)             if C > 100
//   - V  = front lower end        = (0,C)                    if C ≤ 100
//                                 = (C-100, 100)             if C > 100
//   - Sb = (0,100)                (parked at V when C ≤ 100)
//   - K interior wave vertices between R and V, base lerp(R,V,s), offset (o,o)
//     with o = A·sin(πp)·sin(2π·n·s).
//
// All vertices are piecewise-linear in p (kinks only at C = 100, i.e. p = 0.5),
// so a 10% keyframe grid reproduces the intended motion exactly; the sine
// envelope is sampled densely enough at 10% steps to stay smooth.
//
// Run:  node scripts/gen-theme-wave.mjs

const K = 16; // interior wave vertices
const N = 2; // sine periods across the front
const A = 6; // wave amplitude (% of viewport, applied along the diagonal)

function verts(p) {
  const C = 200 * p;
  const r = (v) => Math.round(v * 100) / 100;
  const T = [Math.min(C, 100), 0];
  const R = C <= 100 ? [C, 0] : [100, C - 100];
  const V = C <= 100 ? [0, C] : [C - 100, 100];
  const Sb = C <= 100 ? V : [0, 100];
  const amp = A * Math.sin(Math.PI * p);
  const out = [[0, 0], T, R];
  for (let i = 1; i <= K; i++) {
    const s = i / (K + 1);
    const o = amp * Math.sin(2 * Math.PI * N * s);
    out.push([R[0] + (V[0] - R[0]) * s + o, R[1] + (V[1] - R[1]) * s + o]);
  }
  out.push(V, Sb);
  return out.map(([x, y]) => [r(x), r(y)]);
}

// shoelace signed area — must stay > 0 (counter-clockwise) at every p
function area(vs) {
  let s = 0;
  for (let i = 0; i < vs.length; i++) {
    const [x1, y1] = vs[i];
    const [x2, y2] = vs[(i + 1) % vs.length];
    s += x1 * y2 - x2 * y1;
  }
  return s / 2;
}

const lines = [];
lines.push("/* Generated by scripts/gen-theme-wave.mjs — wavy wavefront reveal");
lines.push("   (top-left corner → bottom-right). Edit the constants above and");
lines.push("   re-run the script instead of hand-editing this block. */");
lines.push("@keyframes theme-wipe-in {");
for (let j = 0; j <= 10; j++) {
  const p = j / 10;
  const vs = verts(p);
  const a = area(vs);
  if (a < 0) throw new Error(`negative area ${a} at p=${p}`);
  const clipped = vs.every(([x, y]) => x > -15 && x < 115 && y > -15 && y < 115);
  if (!clipped) throw new Error(`vertex out of range at p=${p}`);
  const shape = vs.map(([x, y]) => `${x}% ${y}%`).join(", ");
  const op = p === 0 ? "    opacity: 0;" : p === 1 ? "    opacity: 1;" : "";
  lines.push(`  ${Math.round(p * 100)}% {`);
  lines.push(`    clip-path: polygon(${shape});`);
  if (op) lines.push(op);
  lines.push("  }");
}
lines.push("}");
console.log(lines.join("\n"));
